import pandas as pd
import numpy as np

np.random.seed(42)

n = 1000

data = {
    "CustomerID": range(1001, 1001 + n),
    "Age": np.random.randint(18, 70, n),
    "TenureMonths": np.random.randint(1, 61, n),
    "MonthlyCharges": np.round(np.random.uniform(20, 150, n), 2),
    "Contract": np.random.choice(
        ["Monthly", "One Year", "Two Year"],
        n,
        p=[0.55, 0.25, 0.20]
    ),
    "PaymentMethod": np.random.choice(
        ["Credit Card", "Debit Card", "Bank Transfer", "UPI"],
        n
    ),
    "SupportCalls": np.random.randint(0, 10, n),
    "UsageHours": np.round(np.random.uniform(5, 100, n), 1),
}

df = pd.DataFrame(data)

# Create churn based on customer behavior
churn_probability = (
    0.15
    + (df["Contract"] == "Monthly") * 0.20
    + (df["TenureMonths"] < 12) * 0.15
    + (df["SupportCalls"] >= 6) * 0.15
    + (df["MonthlyCharges"] > 100) * 0.10
    - (df["TenureMonths"] > 36) * 0.10
)

churn_probability = np.clip(churn_probability, 0.05, 0.85)

df["Churn"] = np.random.binomial(1, churn_probability)

# Calculate total revenue generated by each customer
df["TotalRevenue"] = np.round(
    df["MonthlyCharges"] * df["TenureMonths"], 2
)

# Save dataset
df.to_csv("data/customer_data.csv", index=False)

print("Dataset created successfully!")
print(f"Number of customers: {len(df)}")
print("\nFirst 5 rows:")
print(df.head())